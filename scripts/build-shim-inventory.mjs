#!/usr/bin/env node
/**
 * US-1 (93-runtime-logic-to-core) — inventory the `shared/` re-export shims.
 *
 * `shared/` is no longer a source tree; it is a compatibility surface. Almost every
 * file in it is a one-line re-export pointing at the module's real home in
 * `packages/core/src` or `packages/babylon/src`. The platform, the export pipeline,
 * and every `@shared/*` alias resolve THROUGH these shims.
 *
 * When `@insimul/core` is eventually extracted into its own repository, each
 * `@shared/*` alias has to be repointed at whichever side of the split its shim
 * lands on — so the split has to be written down BEFORE the big move in US-3, not
 * reconstructed afterwards. This script writes `shared/SHIM_INVENTORY.json`:
 *
 *   core     — shim re-exports into packages/core/src   → alias follows @insimul/core
 *   babylon  — shim re-exports into packages/babylon/src → alias stays with the runtime repo
 *   mixed    — shim reaches BOTH (needs a manual decision at extraction time)
 *   source   — a real (non-shim) shared/ file; see shared/GRANDFATHERED_SOURCE.json
 *
 * Regenerate with: npm run shims:inventory
 * Drift-guarded by shared/__tests__/import-hygiene.test.ts.
 */
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join, resolve, relative, sep } from 'node:path';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const SHARED = join(ROOT, 'shared');
const OUT = join(SHARED, 'SHIM_INVENTORY.json');

const SKIP_DIRS = new Set(['node_modules', 'dist', 'templates', '.git', '__tests__']);

const CORE_TARGET = ['packages', 'core', 'src'].join('/');
const BABYLON_TARGET = ['packages', 'babylon', 'src'].join('/');

function walk(dir, out = []) {
  for (const entry of readdirSync(dir, { withFileTypes: true })) {
    if (entry.name.startsWith('.')) continue;
    const p = join(dir, entry.name);
    if (entry.isDirectory()) {
      if (!SKIP_DIRS.has(entry.name)) walk(p, out);
    } else if (/\.(ts|tsx)$/.test(entry.name) && !/\.test\.tsx?$/.test(entry.name)) {
      out.push(p);
    }
  }
  return out;
}

/** Strip comments so a `packages/core/src` mentioned in a shim's header note isn't counted. */
function stripComments(src) {
  return src.replace(/\/\*[\s\S]*?\*\//g, '').replace(/(^|[^:])\/\/[^\n]*/g, '$1');
}

/**
 * Classify one shared/ file by where its import/export specifiers physically resolve.
 * Uses the RESOLVED path (not the raw specifier) so a `../../packages/core/src/x` and a
 * `../packages/core/src/x` at a different depth classify identically.
 */
export function classifyShimFile(absPath) {
  const body = stripComments(readFileSync(absPath, 'utf8'));
  const specifiers = [...body.matchAll(/(?:from|import|require)\s*\(?\s*['"]([^'"]+)['"]/g)].map((m) => m[1]);

  let core = false;
  let babylon = false;
  for (const spec of specifiers) {
    if (!spec.startsWith('.')) continue;
    const rel = relative(ROOT, resolve(dirname(absPath), spec)).split(sep).join('/');
    if (rel.startsWith(`${CORE_TARGET}/`)) core = true;
    else if (rel.startsWith(`${BABYLON_TARGET}/`)) babylon = true;
  }

  if (core && babylon) return 'mixed';
  if (core) return 'core';
  if (babylon) return 'babylon';
  return 'source';
}

export function buildInventory() {
  const files = walk(SHARED).sort();
  const shims = { core: [], babylon: [], mixed: [], source: [] };
  for (const abs of files) {
    const rel = relative(ROOT, abs).split(sep).join('/');
    shims[classifyShimFile(abs)].push(rel);
  }
  return {
    description:
      'Inventory of shared/ re-export shims by the package they resolve INTO — the map the ' +
      'eventual @insimul/core repo extraction uses to decide which @shared/* aliases follow ' +
      'core and which stay with the Babylon runtime. Generated by scripts/build-shim-inventory.mjs ' +
      '(npm run shims:inventory); drift-guarded by shared/__tests__/import-hygiene.test.ts. ' +
      'Excludes __tests__/ and *.test.ts. "source" = a real shared/ module that has not been ' +
      'moved yet (cross-check shared/GRANDFATHERED_SOURCE.json).',
    legend: {
      core: 'Re-exports into packages/core/src — the @shared/* alias must be repointed at @insimul/core when core is extracted.',
      babylon: 'Re-exports into packages/babylon/src — the alias stays with the runtime repo.',
      mixed: 'Reaches BOTH packages; needs a manual decision at extraction time.',
      source: 'Not a shim — real source still living in shared/.',
    },
    counts: {
      core: shims.core.length,
      babylon: shims.babylon.length,
      mixed: shims.mixed.length,
      source: shims.source.length,
      total: files.length,
    },
    shims,
  };
}

// Only write when run directly (the drift guard imports buildInventory()).
if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const inventory = buildInventory();
  writeFileSync(OUT, `${JSON.stringify(inventory, null, 2)}\n`);
  const { core, babylon, mixed, source, total } = inventory.counts;
  console.log(`shared/SHIM_INVENTORY.json written: ${total} files — ` + `${core} core, ${babylon} babylon, ${mixed} mixed, ${source} source.`);
}
