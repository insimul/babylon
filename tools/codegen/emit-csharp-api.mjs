// emit-csharp-api.mjs — emit a C# REST client from the vendored OpenAPI spec (US-CG4).
//
// Target:    packages/unity/Runtime/Generated/Api/InsimulApiClient.cs
// Namespace: Insimul.Generated.Api  (System.Net.Http + System.Text.Json)
//
// Why a custom emitter instead of NSwag / openapi-generator via npx:
//   - The codegen drift guard requires BYTE-IDENTICAL, offline, deterministic
//     output. openapi-generator (Java) / NSwag emit version-stamped boilerplate and
//     pull network/toolchain deps — fighting the guard. This follows the same
//     decision already made for the GDScript emitter (no deterministic offline tool
//     for the target, so hand-roll a small one). The generated client targets
//     System.Net.Http (transport-agnostic); the Unity plugin adapts it to
//     UnityWebRequest at the boundary — see the Generated/Api README and the
//     existing InsimulHttpClient.cs pattern.
//
// Streaming (text/event-stream) operations return the raw HttpResponseMessage so
// the caller reads the SSE frames; JSON operations return the deserialized model.

import { mkdirSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { loadSpec, collectOperations } from './openapi-spec.mjs';

const NAMESPACE = 'Insimul.Generated.Api';
const OUT_REL = join('packages', 'unity', 'Runtime', 'Generated', 'Api', 'InsimulApiClient.cs');

const BANNER = [
  '// -----------------------------------------------------------------------------',
  '// <auto-generated>',
  '//   GENERATED FILE — DO NOT EDIT BY HAND.',
  '//   Regenerate with:  npm run codegen   (from the insimul-runtime root)',
  '//   Source of truth:  packages/core/openapi/insimul-v1.yaml (vendored platform spec)',
  '//   Emitter:          tools/codegen/emit-csharp-api.mjs (System.Net.Http, System.Text.Json)',
  '// </auto-generated>',
  '// -----------------------------------------------------------------------------',
  '',
].join('\n');

/** camelCase / snake JSON key -> PascalCase C# identifier. */
function pascal(name) {
  return name
    .replace(/[^A-Za-z0-9]+/g, ' ')
    .replace(/([a-z0-9])([A-Z])/g, '$1 $2')
    .split(' ')
    .filter(Boolean)
    .map((w) => w.charAt(0).toUpperCase() + w.slice(1))
    .join('');
}

/** Map a JSON Schema property to a C# type (nullable-aware). */
function csType(schema, required) {
  let base;
  if (schema.format === 'binary') base = 'byte[]';
  else if (schema.type === 'boolean') base = 'bool';
  else if (schema.type === 'integer') base = 'long';
  else if (schema.type === 'number') base = 'double';
  else if (schema.type === 'array') base = 'List<object>';
  else if (schema.type === 'object') base = 'Dictionary<string, object>';
  else base = 'string';

  const isValueType = base === 'bool' || base === 'long' || base === 'double';
  if (!required) return isValueType ? `${base}?` : `${base}?`;
  return base;
}

/** Emit a C# model class for a component schema. */
function emitModel(name, schema) {
  const required = new Set(schema.required ?? []);
  const props = schema.properties ?? {};
  const lines = [`    public class ${name}`, '    {'];
  for (const key of Object.keys(props)) {
    const isReq = required.has(key);
    const type = csType(props[key], isReq);
    // Required reference types get `= null!;` so `<Nullable>enable</Nullable>` doesn't
    // flag CS8618 on the DTO (standard generated-model idiom).
    const isValueType = type === 'bool' || type === 'long' || type === 'double';
    const init = isReq && !isValueType ? ' = null!;' : '';
    lines.push(`        [JsonPropertyName("${key}")]`);
    lines.push(`        public ${type} ${pascal(key)} { get; set; }${init}`);
    lines.push('');
  }
  if (lines[lines.length - 1] === '') lines.pop();
  lines.push('    }');
  return lines.join('\n');
}

/** True when a 2xx response is a JSON body referencing a component schema. */
function jsonResponse(op) {
  return op.responseContentType === 'application/json' && op.responseSchema;
}

/** Emit one client method for an operation. */
function emitMethod(op) {
  const methodName = pascal(op.operationId) + 'Async';
  const httpMethod = `HttpMethod.${pascal(op.method.toLowerCase())}`;
  const body = op.requestBody;
  const returnsJson = jsonResponse(op);
  const returnType = returnsJson ? op.responseSchema : 'HttpResponseMessage';

  const params = [];
  if (body) params.push(`${body.schema} body`);
  params.push('CancellationToken cancellationToken = default');

  const lines = [];
  if (op.summary) lines.push(`        /// <summary>${op.summary}</summary>`);
  lines.push(
    `        public async Task<${returnType}> ${methodName}(${params.join(', ')})`,
  );
  lines.push('        {');
  lines.push(
    `            using var request = new HttpRequestMessage(${httpMethod}, _baseUrl + "${op.path}");`,
  );

  if (body && body.contentType === 'application/json') {
    lines.push(
      '            request.Content = new StringContent(',
      '                JsonSerializer.Serialize(body, JsonOptions), Encoding.UTF8, "application/json");',
    );
  } else if (body && body.contentType === 'multipart/form-data') {
    lines.push('            var form = new MultipartFormDataContent();');
    const schema = loadSpec().components?.schemas?.[body.schema] ?? { properties: {} };
    for (const key of Object.keys(schema.properties ?? {})) {
      const prop = schema.properties[key];
      const getter = pascal(key);
      if (prop.format === 'binary') {
        lines.push(
          `            if (body.${getter} != null)`,
          `                form.Add(new ByteArrayContent(body.${getter}), "${key}", "${key}");`,
        );
      } else {
        lines.push(
          `            if (body.${getter} != null)`,
          `                form.Add(new StringContent(body.${getter}), "${key}");`,
        );
      }
    }
    lines.push('            request.Content = form;');
  }

  if (returnsJson) {
    lines.push(
      '            var response = await _http.SendAsync(request, cancellationToken).ConfigureAwait(false);',
      '            response.EnsureSuccessStatusCode();',
      '            var json = await response.Content.ReadAsStringAsync().ConfigureAwait(false);',
      `            return JsonSerializer.Deserialize<${returnType}>(json, JsonOptions)!;`,
    );
  } else {
    // Streaming / non-JSON: hand the response back so the caller reads the SSE frames.
    lines.push(
      '            return await _http.SendAsync(',
      '                request, HttpCompletionOption.ResponseHeadersRead, cancellationToken).ConfigureAwait(false);',
    );
  }
  lines.push('        }');
  return lines.join('\n');
}

/**
 * Generate the C# API-client source text (deterministic; no filesystem writes).
 * @returns {string}
 */
export function generateCSharpApi() {
  const spec = loadSpec();
  const ops = collectOperations(spec);
  const schemas = spec.components?.schemas ?? {};

  const models = Object.keys(schemas).map((name) => emitModel(name, schemas[name]));
  const methods = ops.map(emitMethod);

  const src = [
    'using System;',
    'using System.Collections.Generic;',
    'using System.Net.Http;',
    'using System.Text;',
    'using System.Text.Json;',
    'using System.Text.Json.Serialization;',
    'using System.Threading;',
    'using System.Threading.Tasks;',
    '',
    `namespace ${NAMESPACE}`,
    '{',
    models.join('\n\n'),
    '',
    '    /// <summary>',
    '    /// Transport-agnostic REST client generated from the Insimul OpenAPI v1 spec.',
    '    /// Uses System.Net.Http; the Unity plugin adapts it to UnityWebRequest at the',
    '    /// boundary (see Generated/Api/README.md and InsimulHttpClient.cs).',
    '    /// </summary>',
    '    public class InsimulApiClient',
    '    {',
    '        private readonly HttpClient _http;',
    '        private readonly string _baseUrl;',
    '',
    '        private static readonly JsonSerializerOptions JsonOptions = new JsonSerializerOptions',
    '        {',
    '            PropertyNameCaseInsensitive = true,',
    '            DefaultIgnoreCondition = JsonIgnoreCondition.WhenWritingNull,',
    '        };',
    '',
    '        public InsimulApiClient(HttpClient http, string baseUrl)',
    '        {',
    '            _http = http ?? throw new ArgumentNullException(nameof(http));',
    '            _baseUrl = (baseUrl ?? string.Empty).TrimEnd(\'/\');',
    '        }',
    '',
    methods.join('\n\n'),
    '    }',
    '}',
  ].join('\n');

  return BANNER + src.replace(/\s*$/, '') + '\n';
}

/**
 * Write the C# API client under `baseDir` and return written paths.
 * @param {string} baseDir
 * @returns {string[]}
 */
export function emitCSharpApi(baseDir) {
  const outDir = join(baseDir, 'packages', 'unity', 'Runtime', 'Generated', 'Api');
  mkdirSync(outDir, { recursive: true });
  writeFileSync(join(baseDir, OUT_REL), generateCSharpApi());
  return [OUT_REL];
}
